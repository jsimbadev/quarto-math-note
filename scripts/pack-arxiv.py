#!/usr/bin/env python3
"""Package Quarto XeLaTeX output and common dependencies; independently test before submission."""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
root = Path(__file__).resolve().parent.parent
candidate = [root / '_output/index.tex', root / 'index.tex']
source = next((p for p in candidate if p.exists()), None)
if source is None:
    raise SystemExit('No index.tex found; run make arxiv with Quarto installed.')
output = root / '_output/arxiv-source.zip'
files = {'index.tex': source}
for directory in ('figures', 'tex'):
    folder = root / directory
    if folder.exists():
        for entry in folder.rglob('*'):
            if entry.is_file() and entry.suffix.lower() in ('.png', '.pdf', '.jpg', '.jpeg', '.eps', '.tex'):
                files[entry.relative_to(root).as_posix()] = entry
for name in ('macros.tex', 'references.bib'):
    path = root / name
    if path.exists():
        files[name] = path
with ZipFile(output, 'w', ZIP_DEFLATED) as archive:
    for target, path in sorted(files.items()):
        archive.write(path, target)
    archive.writestr('README-arxiv.txt',
                     'Source generated by Quarto using XeLaTeX. Verify extracted compilation, '
                     'bibliography and dependencies before submitting.\n')
print(f'Wrote {output} with {len(files)} source files.')
